"""Tests for a resolved call site, generated from the decision's failure bank and reference cases.

Deterministic: one fixed template, the cases inserted as Python literals; no model writes code.
Each generated test loads the call site's module with a fake `openai` module in its place (so
the model call is mocked and nothing reaches the network), calls the site's function with the
case's input and checks that

  - exactly one request is made, to the new model (and the new provider's base URL);
  - fed the case's reference answer as the reply, the function returns that answer (only for
    the fit-checked call site, whose inputs the cases are).

A method site (Class.method) is called on an instance: the class's no-arg constructor if it
has one, else one built with __init__ mocked to a no-op and its attributes set from the case's
inputs. When neither reaches the model the test is skipped with the reason (resolve lists it in
the PR); so is a non-fit-checked function whose parameters the case's inputs don't fit.

A failure-bank case without a reference is replayed with its banked (failing) output: the
request must still go to the new model; how the code handles a bad reply is not asserted.
resolve runs the file before the edit (the old code: routing fails) and after it.
"""
from __future__ import annotations

import json
import os
import pprint
import re
import subprocess
import sys
from pathlib import Path

# sample-row keys that are not inputs of the call site's function
NOT_ARGS = {"id", "hard", "tags", "user_message", "reference", "source", "from_failure_bank",
            "generated_by", "generated_at", "added_at"}

TEMPLATE = '''"""Generated by `notbydefault resolve {decision_id}`: decision #{decision_id}'s
failure-bank and reference cases against the call site(s) it switches to {target}.

Deterministic template; the model call is mocked with a fake `openai` module (no network).
Regenerate with resolve rather than editing by hand."""
import datetime
import importlib.util
import inspect
import sys
import types
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[{depth}]
EXPECT = {expect}
KEY_ENVS = {keys}
SITES = {sites}
CASES = {cases}


def _fake_openai(reply):
    clients = []

    class Completions:
        def __init__(self):
            self.requests = []

        def create(self, **kw):
            self.requests.append(kw)
            message = types.SimpleNamespace(role="assistant", content=reply)
            return types.SimpleNamespace(
                choices=[types.SimpleNamespace(message=message, finish_reason="stop")],
                usage=None)

    class OpenAI:
        def __init__(self, **kw):
            self.kwargs = kw
            self.chat = types.SimpleNamespace(completions=Completions())
            clients.append(self)

    module = types.ModuleType("openai")
    module.OpenAI = OpenAI
    return module, clients


@pytest.fixture
def isolated_modules():
    """Modules the call site imports are dropped afterwards, so each case starts fresh."""
    before = set(sys.modules)
    yield
    for name in set(sys.modules) - before:
        del sys.modules[name]


def _load(path, monkeypatch, fake):
    monkeypatch.setitem(sys.modules, "openai", fake)
    monkeypatch.syspath_prepend(str((ROOT / path).parent))
    spec = importlib.util.spec_from_file_location("_nbd_site_" + Path(path).stem, ROOT / path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _value(annotation, value):
    kind = getattr(annotation, "__name__", annotation)
    if isinstance(value, str) and kind in ("date", "datetime.date"):
        return datetime.date.fromisoformat(value)
    if isinstance(value, str) and kind in ("datetime", "datetime.datetime"):
        return datetime.datetime.fromisoformat(value)
    return value


def _args(fn, case):
    """Parameters named like a case field get that field; the rest the case's user message."""
    args = {{}}
    for name, p in inspect.signature(fn).parameters.items():
        if p.kind in (p.VAR_POSITIONAL, p.VAR_KEYWORD):
            continue
        if name in case["fields"]:
            args[name] = _value(p.annotation, case["fields"][name])
        elif p.default is p.empty:
            args[name] = case["user_message"]
    return args


def _instance(cls, how, case, monkeypatch):
    """An instance for a method site: the class's no-arg constructor, or (how == "mocked
    __init__") __init__ replaced by a no-op and the instance's attributes set from the case:
    its fields, and each __init__ parameter (a field, its default, else the user message)."""
    if how == "constructor":
        return cls()
    params = inspect.signature(cls.__init__).parameters
    monkeypatch.setattr(cls, "__init__", lambda self, *a, **kw: None)
    obj = cls()
    for name, p in list(params.items())[1:]:
        if p.kind in (p.VAR_POSITIONAL, p.VAR_KEYWORD):
            continue
        value = case["fields"].get(name, case["user_message"] if p.default is p.empty
                                   else p.default)
        setattr(obj, name, _value(p.annotation, value))
    for name, value in case["fields"].items():
        if not hasattr(obj, name):
            setattr(obj, name, value)
    return obj


def _requests(clients):
    return [r for c in clients for r in c.chat.completions.requests]


@pytest.mark.parametrize("site", SITES, ids=[s["id"] for s in SITES])
@pytest.mark.parametrize("case", CASES, ids=[c["id"] for c in CASES])
def test_case_reaches_the_new_model(site, case, monkeypatch, isolated_modules):
    for key in KEY_ENVS:
        monkeypatch.setenv(key, "test-key")
    fake, clients = _fake_openai(case["reply"])
    module = _load(site["path"], monkeypatch, fake)
    *owner, name = site["symbol"].split(".")
    tried = []
    for how in (["constructor", "mocked __init__"] if owner else ["function"]):
        try:
            target = module
            for part in owner:
                target = getattr(target, part)
            fn = getattr(_instance(target, how, case, monkeypatch) if owner else target, name)
            result = fn(**_args(fn, case))
        except Exception as e:     # judged below: did it reach the model, what did it return
            result = e
        if _requests(clients):
            break
        tried.append(f"{{how}}: {{type(result).__name__}}: {{result}}"[:200])
    requests = _requests(clients)
    if not requests and (owner or not site["primary"]):   # the case's inputs can't drive it
        pytest.skip(f"{{site['symbol']}} not reached: {{'; '.join(tried)}}")
    assert len(requests) == 1, f"expected one model call, got {{len(requests)}} ({{result!r}})"
    assert requests[0].get("model") == EXPECT["model"]
    if EXPECT["base_url"]:
        assert [c.kwargs.get("base_url") for c in clients] == [EXPECT["base_url"]]
    if site["primary"] and case["expect"] is not None:
        assert not isinstance(result, Exception), f"{{type(result).__name__}}: {{result}}"
        expect = case["expect"]
        assert result == expect or (isinstance(expect, dict) and result in expect.values())
'''


def test_path(project: Path, decision_id: int) -> Path:
    return Path(project) / "tests" / f"test_nbd_{decision_id}_generated.py"


def _reply(value) -> str:
    return value if isinstance(value, str) else json.dumps(value, ensure_ascii=False)


def cases(project: Path, decision_id: int, samples: list[dict]) -> list[dict]:
    """Failure-bank cases first, then reference cases; one per input."""
    from notbydefault.fit import failures as failures_mod
    banked: dict[str, str] = {}
    for r in failures_mod.load(Path(project), decision_id):
        banked.setdefault(r["input"], r["output"])
    out, seen = [], set()
    for s in samples:
        msg = s["user_message"]
        from_bank = msg in banked or s.get("from_failure_bank")
        ref = s.get("reference")
        if msg in seen or (not from_bank and ref is None):
            continue
        seen.add(msg)
        reply = _reply(ref) if ref is not None else banked.get(msg, "")
        cid = re.sub(r"\W+", "-", str(s.get("id") or f"case-{len(out) + 1}")).strip("-")
        out.append({"id": cid, "source": "failure bank" if from_bank else "reference",
                    "user_message": msg, "fields": {k: v for k, v in s.items()
                                                    if k not in NOT_ARGS},
                    "reply": reply, "expect": ref})
    return out


def render(project: Path, decision_id: int, target: str, sites, primary: str | None,
           case_rows: list[dict], expect: dict, key_envs: list[str]) -> str:
    """The test file's text. `sites` are resolve Sites with a symbol (a function or
    Class.method); `primary` is the fit-checked one."""
    path = test_path(project, decision_id)
    depth = len(path.relative_to(Path(project)).parts) - 1
    site_rows = [{"id": f"{s.path}:{s.symbol}", "path": s.path, "symbol": s.symbol,
                  "primary": s.describe() == primary}
                 for s in sites if s.symbol]

    def lit(v):
        return pprint.pformat(v, width=96, sort_dicts=False)
    return TEMPLATE.format(decision_id=decision_id, target=target, depth=depth,
                           expect=lit(expect), keys=lit(sorted(set(key_envs))),
                           sites=lit(site_rows), cases=lit(case_rows))


def run(project: Path, path: Path, timeout: float = 600) -> dict:
    """Run one generated test file; {"passed", "failed", "errors", "total", "summary"}."""
    env = dict(os.environ, PYTHONDONTWRITEBYTECODE="1")
    # serial and no cache dir, but no -x: the counts need every case run
    proc = subprocess.run([sys.executable, "-m", "pytest", "-q", "-rs", "-p",
                           "no:cacheprovider", "--no-header", str(path)], cwd=str(project),
                          capture_output=True, timeout=timeout, env=env)
    text = proc.stdout.decode("utf-8", "replace") + proc.stderr.decode("utf-8", "replace")
    lines = text.strip().splitlines()
    summary = lines[-1].strip("= ") if lines else f"exit {proc.returncode}"
    counts = {k: 0 for k in ("passed", "failed", "errors", "skipped")}
    for n, word in re.findall(r"(\d+) (passed|failed|errors?|skipped)\b", summary):
        counts["errors" if word.startswith("error") else word] += int(n)
    counts["total"] = counts["passed"] + counts["failed"] + counts["errors"]
    # "SKIPPED [3] tests/x.py:120: Handler.do_POST not reached: ..." (-rs), one per reason
    counts["skip_reasons"] = sorted({m.strip() for m in
                                     re.findall(r"^SKIPPED \[\d+\] [^:]+:\d+: (.*)$", text,
                                                re.MULTILINE)})
    counts["summary"] = summary
    return counts


def counts_text(c: dict | None) -> str:
    if not c:
        return "-"
    extra = (f", {c['errors']} error(s)" if c.get("errors") else "") \
        + (f", {c['skipped']} skipped" if c.get("skipped") else "")
    return f"{c['passed']}/{c['total']} passed{extra}"
